// Helper untuk offset tanggal acak dari sekarang (X hari lalu)
function daysAgo(days: number, hourOffset: number = 10): string {
  const date = new Date();
  date.setDate(date.getDate() - days);
  date.setHours(hourOffset, 15, 0, 0);
  return date.toISOString();
}

